export function translate(language: Language, key: TranslationKey, values: Record<string, string | number> = {}): string {
  const template = (language === "zh" ? ZH : EN)[key];
  return template.replace(/\{(\w+)\}/gu, (match, name: string) => String(values[name] ?? match));
}

